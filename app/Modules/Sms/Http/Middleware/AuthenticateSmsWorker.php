<?php

namespace App\Modules\Sms\Http\Middleware;

use Closure;
use Illuminate\Http\Request;
use Symfony\Component\HttpFoundation\Response;

/**
 * البوابة الوحيدة أمام طابور فيه رموز تحقق صريحة.
 *
 * ═══ لماذا هذا الملف أخطر ما في الوحدة ═══
 *
 * نقطة `‎/sms/claim‎` تُرجع رقم هاتف ونصّ رسالةٍ يحمل رمز توثيق. ومن
 * يصل إليها بلا حراسة **يوثّق أي حساب في المنصة**: يطلب استعادة كلمة
 * مرور لأي رقم، ثم يسحب الرمز من الطابور قبل أن يسحبه الهاتف.
 *
 * أي أن غياب سطرٍ واحد هنا يُسقط كل ما بُني في `PhoneVerificationService`
 * من تجزئة وصلاحية وسقف محاولات.
 *
 * ═══ سرٌّ ثابت لا رمز Sanctum ═══
 *
 * البديل المرفوض: إصدار رمز شخصي لحسابٍ يمثّل الهاتف. مرفوض لسببين:
 *
 * 1. **العامل ليس شخصاً.** حسابٌ له يعني بيانات دخول تفتح كل ما يفتحه
 *    أي مستخدم — النشر والمحادثات والحذف. وضبط ذلك يحتاج صلاحيات على
 *    الرمز، وهي غير مبنيّة بعد (كل الرموز تُصدَر بـ`['*']`).
 * 2. **`auth:sanctum` يقبل الرمز في كل مسار.** رمزٌ لكيانٍ غير `User`
 *    يُوثَّق في كل نقطة نهاية محروسة، فيصل إلى متحكّمات تتوقع مستخدماً.
 *
 * ═══ hash_equals لا === ═══
 *
 * المقارنة النصّية تخرج عند أول محرف مختلف، وزمنها يكشف كم محرفاً
 * طابق. والفرق ميكروثوانٍ — يُقاس عبر آلاف الطلبات، وهو ما يفعله من
 * يهاجم بلا عجلة.
 *
 * ═══ ولا رسالة تفرّق بين «لا رمز» و«رمز خاطئ» ═══
 *
 * 401 واحدة في الحالتين: أي تمييز يقول للمهاجم إن ترويسته وصلت وإن
 * الشكل صحيح، فيبقى له التخمين وحده.
 */
class AuthenticateSmsWorker
{
    public function handle(Request $request, Closure $next): Response
    {
        $expected = (string) config('sms.worker.token', '');
        $given = (string) ($request->bearerToken() ?? '');

        /**
         * السرّ الفارغ يرفض كل شيء — لا يقبل كل شيء.
         *
         * بلا هذا الشرط يطابق `hash_equals('', '')` طلباً بلا ترويسة
         * على تهيئةٍ نسيت المفتاح، فينفتح الطابور للعالم بصمت. ونفس
         * الحالة يمنعها `SmsServiceProvider` عند الإقلاع؛ وهذا الشرط
         * حارسٌ ثانٍ لأن الأول يُعطَّل بتعديل إعداد.
         */
        if ($expected === '' || $given === '' || ! hash_equals($expected, $given)) {
            return response()->json([
                'message' => 'غير مصرَّح.',
                'code' => 'sms_worker_unauthorized',
            ], 401);
        }

        return $next($request);
    }
}
