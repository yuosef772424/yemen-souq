<?php

namespace App\Modules\Sms\Enums;

/**
 * قناة التوصيل الصادرة.
 *
 * ═══ القناتان في نفس الطابور، والمُوصِّلان مختلفان تماماً ═══
 *
 *   Sms      الهاتف **يسحب** من الخادم ويرسل ببطاقته
 *   WhatsApp الخادم **يدفع** إلى واجهة واتساب، ولا يمرّ بالهاتف إطلاقاً
 *
 * ولماذا لا يمرّ واتساب بالهاتف: لا يوجد `termux-whatsapp-send`، وفتح
 * `wa.me` بنيّة أندرويد يفتح المحادثة وينتظر ضغطة إرسال بشرية — أي أنه
 * ليس أتمتةً بل تذكيراً.
 *
 * ═══ ورغم ذلك، صفّ واحد وحالات خمس ═══
 *
 * البديل المرفوض: جدولان. مرفوض لأن كل ما حول التوصيل مشترك — الأجل،
 * وعدّ المحاولات، والسحب الذرّي، واستعادة السحبة الميتة، والتراجع من
 * قناة إلى أخرى. وجدولان يعني نسختين من كل ذلك، ثم سؤالاً لا جواب له:
 * «هل وصل الرمز؟» يحتاج قراءة الاثنين ودمجهما.
 *
 * والمُوصِّل تفصيلُ من يسحب: عاملُ تيرمكس يسحب `sms`، ومهمّةُ الطابور
 * تسحب `whatsapp` باسم عاملٍ ثابت. نفس النداء، نفس الشرط الذرّي.
 */
enum DeliveryChannel: string
{
    case Sms = 'sms';
    case WhatsApp = 'whatsapp';

    public function label(): string
    {
        return match ($this) {
            self::Sms => 'رسالة نصية',
            self::WhatsApp => 'واتساب',
        };
    }

    /**
     * هل يسحبها هاتفٌ خارجي، أم يدفعها الخادم؟
     *
     * الفرق عمليّ لا وصفيّ: القناة المسحوبة تنتظر هاتفاً قد ينام،
     * والمدفوعة تنتظر طابور لارافل. وتشخيص «لماذا لم تصل» يبدأ من هنا.
     */
    public function isPulled(): bool
    {
        return $this === self::Sms;
    }

    /** اسم العامل الثابت للقنوات المدفوعة — يُكتب في claimed_by */
    public function serverWorker(): string
    {
        return match ($this) {
            self::WhatsApp => 'whatsapp-dispatcher',
            self::Sms => 'unknown',
        };
    }

    /**
     * القناة التالية عند استنفاد المحاولات — من الإعداد لا من ترتيب ثابت.
     *
     * والخريطة ليست دائرية بقصد: فشلُ واتساب يعني أن الرقم بلا واتساب،
     * وإعادته إلى SMS الذي فشل أصلاً دورانٌ بلا فائدة يستهلك محاولات
     * ويؤخّر رسالةً أخرى في الطابور.
     */
    public function failover(): ?self
    {
        $next = config("sms.failover.{$this->value}");

        if (! is_string($next) || $next === '') {
            return null;
        }

        return self::tryFrom($next);
    }
}
