#!/bin/sh
#
# ما يجري قبل كل خدمة — الويب والعامل والمجدول معاً.
#
# ═══ لماذا التخبئة هنا لا في Dockerfile ═══
#
# `config:cache` يُجمّد قيم `env()` وقت تشغيله. وتشغيله أثناء البناء يعني
# تجميد قيم بيئة البناء — حيث لا `DB_PASSWORD` ولا `APP_KEY` ولا
# `SMS_WORKER_TOKEN`. فتخرج صورةٌ تحمل إعداداً فارغاً وتبدو سليمة، وأول
# استعلام يفشل باتصال إلى `localhost`.
#
# فالتخبئة عند الإقلاع، بعد أن تكون المنصة قد حقنت متغيّراتها.

set -e

# ═══ APP_URL يُفحص أولاً، وقبل أي أمر artisan ═══
#
# لارافل يبني طلباً وهمياً من `app.url` قبل تنفيذ أي أمر طرفية
# (SetRequestForConsole). فقيمةٌ معطوبة تقتل **كل** أمر قبل أن يبدأ —
# ورسالتها «Invalid URI» من عمق Symfony، لا تذكر APP_URL ولا تدلّ على
# الإعداد إطلاقاً.
#
# وقع هذا فعلاً عند أول نشر: `https://${RAILWAY_PUBLIC_DOMAIN}` والنطاق
# لم يُولَّد بعد، فصارت القيمة `https://` وحدها. الحاوية دخلت حلقة إقلاع
# وفشل، والسجلّ يشير إلى ملف في إطار العمل لا إلى المتغيّر الناقص.
#
# فالفحص هنا يحوّل ذلك إلى رسالة تُقرأ وتُصلَح في دقيقة.
if ! printf '%s' "${APP_URL:-}" | grep -qE '^https?://[A-Za-z0-9]'; then
    echo "خطأ: APP_URL غير صالح — القيمة الحالية: '${APP_URL:-<فارغ>}'" >&2
    echo "يجب أن تبدأ بـhttp:// أو https:// يليها اسم النطاق، بلا مسافات ولا اقتباس." >&2
    echo "مثال: APP_URL=https://your-app.up.railway.app" >&2
    echo "وعلى Railway: ولّد نطاقاً عاماً أولاً (Settings ← Networking ← Generate Domain)." >&2
    exit 1
fi

php artisan config:cache
php artisan route:cache
php artisan view:cache

# ═══ الهجرات على خدمة واحدة فقط ═══
#
# ثلاث خدمات تُقلع معاً من نفس الصورة. ولو هاجرت كلها، تسابقت ثلاث عمليات
# على نفس الجدول — وأخفّ نتيجة ممكنة هجرةٌ نصف مطبَّقة يصعب تشخيصها.
#
# فالمتغيّر يُضبط على خدمة الويب وحدها: RUN_MIGRATIONS=true
if [ "${RUN_MIGRATIONS:-false}" = "true" ]; then
    php artisan migrate --force

    # الرابط يُنشأ بعد الهجرة لا قبلها: نظام الملفات هنا مؤقّت، والرابط
    # يختفي مع كل إعادة نشر — فإنشاؤه عند الإقلاع لا مرةً عند البناء
    php artisan storage:link
fi

# ═══ المنفذ تُمليه المنصة لا الصورة ═══
#
# `SERVER_NAME=:80` في Dockerfile افتراضٌ صالح لمن يوجّه إلى منفذ ثابت.
# لكن Railway (وRender وFly وأمثالها) تحقن `PORT` وتتوقّع الاستماع عليه،
# ولا تستنتج منفذاً ثابتاً إلا من `EXPOSE` — وليس عندنا.
#
# فبلا هذا السطر يستمع FrankenPHP على 80 بينما يوجّه الوسيط إلى منفذ
# آخر: الحاوية حيّة، والخادم يعمل، ولا يصل طلب واحد — ثم يفشل فحص
# الصحة فتُوسم النشرة CRASHED بلا خطأ في أي سجلّ.
#
# وهو نفس العطل الذي حذّر منه تعليق SERVER_NAME في Dockerfile، دخل من
# الباب الآخر: هناك اسمٌ خاطئ، وهنا منفذٌ خاطئ، والعَرَض واحد.
#
# و80 احتياطاً لمن لا يحقن PORT — تشغيل محلي بـdocker run مثلاً.
export SERVER_NAME=":${PORT:-80}"

exec "$@"
