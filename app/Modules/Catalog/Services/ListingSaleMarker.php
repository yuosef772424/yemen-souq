<?php

namespace App\Modules\Catalog\Services;

use App\Modules\Catalog\Models\Listing;

/**
 * تعليم الإعلان مباعاً — وإعادته إلى العرض إن كان ذلك خطأً.
 *
 * ═══ لماذا حالة لا حذف ═══
 *
 * الإعلان المباع ليس إعلاناً خاطئاً. حذفه يمحو تاريخه ومشاهداته
 * وأسئلته وإحصاءاته، وهي بيانات المعلن عن سوقه هو. وscopePublished
 * يشترط active، فتغيير الحالة وحده يُخفيه من البحث والتصفّح بلا لمس
 * أي استعلام — والصف باقٍ في لوحة المعلن.
 *
 * ═══ لماذا قابل للتراجع ═══
 *
 * زرّ واحد يُخفي إعلاناً من السوق كله. ونقرة خاطئة بلا طريق رجوع تعني
 * أن المعلن يعيد النشر من الصفر: عنوان ووصف وصور ومواصفات، ويفقد
 * العدّادات والأسئلة. والتراجع لا يمنح شيئاً لم يكن له — الإعلان يعود
 * إلى ما كان عليه لا أكثر.
 *
 * ═══ لماذا لا يُمَسّ expires_at ═══
 *
 * البيع لا يمدّد الصلاحية. إعلان بِيع قبل انتهائه بيوم يعود — عند
 * التراجع — بيومه الباقي لا بثلاثين يوماً جديدة. التمديد يخصّ التجديد،
 * وله مساره وعدّاده.
 */
final class ListingSaleMarker
{
    /**
     * الحالات التي يصحّ البيع منها.
     *
     * المسودة والمرفوض والمعلَّق لم تُعرض على أحد أصلاً، و«مباع» على ما
     * لم يُنشر ادعاءٌ لا حدث.
     */
    private const SELLABLE = ['active', 'paused'];

    public function markSold(Listing $listing): bool
    {
        if (! in_array($listing->status, self::SELLABLE, true)) {
            return false;
        }

        $listing->forceFill([
            'status' => 'sold',
            'sold_at' => now(),
        ])->save();

        return true;
    }

    /**
     * الرجوع إلى active لا إلى الحالة السابقة.
     *
     * لماذا لا نحفظ الحالة السابقة ونعيدها: الحالة الوحيدة الأخرى التي
     * يصحّ البيع منها هي paused، وإعادة إعلان إلى «موقوف» بعد تراجع عن
     * البيع تُبقيه مخفياً — فيبدو الزرّ كأنه لم يعمل. والمعلن الذي يتراجع
     * يريد إعلانه معروضاً.
     */
    public function unmarkSold(Listing $listing): bool
    {
        if ($listing->status !== 'sold') {
            return false;
        }

        $listing->forceFill([
            'status' => 'active',
            'sold_at' => null,
        ])->save();

        return true;
    }
}
