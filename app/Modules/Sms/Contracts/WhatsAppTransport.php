<?php

namespace App\Modules\Sms\Contracts;

/**
 * توصيل رسالة واتساب واحدة.
 *
 * نفس مبدأ `PhoneVerificationSender`: العقد يوصّل، والسياسة كلها فوقه —
 * الأجل والمحاولات والتراجع في `SmsOutbox`. فتبديل المزوّد لا يغيّر
 * سلوكاً أمنياً ولا يمسّ الطابور.
 *
 * ═══ لماذا يُمرَّر الرمز منفصلاً عن النصّ ═══
 *
 * واتساب لا يقبل نصّاً حرّاً لبدء محادثة خارج نافذة الأربع والعشرين
 * ساعة: الرسالة تُرسَل بـ**قالب معتمَد** والرمز يُمرَّر معامِلاً له.
 * فلو مرّرنا النصّ المبنيّ ("رمز التحقق: 123456") لاضطرّ المُوصِّل إلى
 * انتزاع الرقم منه بتعبير نمطي — وأول تغيير في صياغة القالب يكسره بصمت.
 *
 * والسائقان الآخران (`log` و`http`) يستعملان النصّ، فيصل الاثنان.
 */
interface WhatsAppTransport
{
    /**
     * @param  string  $to  رقم بصيغة E.164
     * @param  string  $text  النصّ المبنيّ — لمن يقبل نصّاً حرّاً
     * @param  ?string  $code  الرمز وحده — لمن يحتاج معامِل قالب
     *
     * @throws \RuntimeException عند فشل التوصيل، برسالة تصلح للعرض في السجلّ
     */
    public function send(string $to, string $text, ?string $code = null): void;
}
